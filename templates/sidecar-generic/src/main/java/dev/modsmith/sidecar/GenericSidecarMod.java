/**
 * modsmith generic sidecar: one jar, every station.
 *
 * Generated-by-codegen is retired; this mod is compiled once per MC version and reads its
 * stations from config/modsmith-sidecar/&lt;pack&gt;.json. Each station is a "server gives no
 * menu" block: a vanilla-protocol client never receives open_window for it, so the mod looks
 * the recipe up in the server's RecipeManager, checks ingredients, consumes them, waits the
 * cook time, and hands the result to the player. No file, network or reflection access
 * beyond reading the mod's own cook time.
 *
 * The three gates from the per-station era carry over unchanged:
 *   - permission: every command sits behind .requires(hasPermissionLevel(opLevel))
 *   - heat: a station that declares heatTag refuses to cook without a heat source under it
 *   - ingredients: exact item+components match first, item-only fallback second
 */
public final class GenericSidecarMod implements ModInitializer {
    private static final Logger LOG = LoggerFactory.getLogger("modsmith_sidecar");
    private static final int STATION_RANGE = 4;
    private static final List<CookJob> JOBS = new ArrayList<>();

    @Override
    public void onInitialize() {
        List<SidecarStation> stations = loadStations();
        if (stations.isEmpty()) {
            LOG.warn("[modsmith-sidecar] no config under config/modsmith-sidecar/*.json - no commands registered. " +
                    "Put the pack config there (generated by 'modsmith sidecar') and restart the server.");
        }
        for (SidecarStation station : stations) {
            register(station);
        }
        ServerTickEvents.END_SERVER_TICK.register(GenericSidecarMod::tick);
        LOG.info("[modsmith-sidecar] {} station(s) ready: {}", stations.size(),
                stations.stream().map(s -> "/" + s.command).toList());
    }

    private static void register(SidecarStation station) {
        CommandRegistrationCallback.EVENT.register((dispatcher, registryAccess, environment) ->
                dispatcher.register(CommandManager.literal(station.command)
                        .requires(source -> source.hasPermissionLevel(station.opLevel))
                        .then(CommandManager.literal("cook")
                                .then(CommandManager.argument("recipe", StringArgumentType.greedyString())
                                        .executes(ctx -> cook(ctx, StringArgumentType.getString(ctx, "recipe"), station))))
                        .then(CommandManager.literal("list")
                                .executes(ctx -> list(ctx, station)))
                        .then(CommandManager.literal("status")
                                .executes(ctx -> status(ctx, station)))));
    }

    // ---- the three commands, per station ----

    private static int cook(CommandContext<ServerCommandSource> ctx, String rawId, SidecarStation station) {
        ServerCommandSource source = ctx.getSource();
        ServerPlayerEntity player = source.getPlayer();
        if (player == null) {
            return fail(source, "only a player can cook");
        }
        MinecraftServer server = source.getServer();
        ServerWorld world = (ServerWorld) player.getWorld();

        Identifier id = parseRecipeId(rawId, station.recipeType);
        if (id == null) {
            return fail(source, "bad recipe id: " + rawId);
        }
        RecipeEntry<?> entry = findRecipe(server, id);
        if (entry == null) {
            return fail(source, "no such recipe: " + id);
        }
        Recipe<?> recipe = entry.value();
        if (!isOurRecipe(recipe, station.recipeType)) {
            return fail(source, "not a " + station.recipeType + " recipe: " + id);
        }
        BlockPos at = findStation(world, player.getBlockPos(), station.block);
        if (at == null) {
            return fail(source, "no " + station.label + " within " + STATION_RANGE + " blocks");
        }
        if (station.heatTagKey != null && !isHeated(world, at, station.heatTagKey)) {
            return fail(source, station.label + " is not heated: put a heat source (stove / lit campfire) under it");
        }

        List<Ingredient> ingredients = recipe.getIngredients();
        if (ingredients.isEmpty()) {
            return fail(source, "recipe has no ingredients");
        }

        List<ItemStack> planned = snapshot(player);
        for (Ingredient ingredient : ingredients) {
            if (ingredient.isEmpty()) {
                continue;
            }
            if (!takeOne(planned, ingredient.getMatchingStacks())) {
                return fail(source, "missing ingredient: " + describe(ingredient));
            }
        }
        commit(player, planned);

        int cookTime = cookTimeOf(recipe, station.cookTime);
        ItemStack result = recipe.getResult(server.getRegistryManager()).copy();
        JOBS.add(new CookJob(player, result, cookTime));
        LOG.info("[{}] {} cooking {} ({} ticks)", station.command, player.getName().getString(), id, cookTime);
        source.sendFeedback(() -> Text.literal(
                "started " + result.getName().getString() + ", about " + (cookTime / 20) + "s"), false);
        return 1;
    }

    private static int status(CommandContext<ServerCommandSource> ctx, SidecarStation station) {
        ServerCommandSource source = ctx.getSource();
        ServerPlayerEntity player = source.getPlayer();
        if (player == null) {
            return fail(source, "only a player can check");
        }
        ServerWorld world = (ServerWorld) player.getWorld();
        BlockPos at = findStation(world, player.getBlockPos(), station.block);
        if (at == null) {
            source.sendFeedback(() -> Text.literal("no station nearby"), false);
            return 0;
        }
        source.sendFeedback(() -> Text.literal(station.label + " at " + at.toShortString()), false);
        return 1;
    }

    private static int list(CommandContext<ServerCommandSource> ctx, SidecarStation station) {
        ServerCommandSource source = ctx.getSource();
        int total = 0;
        List<String> shown = new ArrayList<>();
        for (RecipeEntry<?> entry : source.getServer().getRecipeManager().values()) {
            if (!isOurRecipe(entry.value(), station.recipeType)) {
                continue;
            }
            total++;
            if (shown.size() < 20) {
                shown.add(entry.id().toString());
            }
        }
        final int count = total;
        source.sendFeedback(() -> Text.literal("recipes: " + count), false);
        for (String rid : shown) {
            source.sendFeedback(() -> Text.literal("  " + rid), false);
        }
        return count;
    }

    // ---- runtime helpers (unchanged from the per-station era) ----

    private static void tick(MinecraftServer server) {
        if (JOBS.isEmpty()) {
            return;
        }
        Iterator<CookJob> it = JOBS.iterator();
        while (it.hasNext()) {
            CookJob job = it.next();
            if (job.player.isRemoved()) {
                it.remove();
                continue;
            }
            if (--job.remaining > 0) {
                continue;
            }
            it.remove();
            ItemStack out = job.output.copy();
            if (!job.player.getInventory().insertStack(out)) {
                job.player.dropItem(out, false);
            }
            job.player.sendMessage(Text.literal("ready: " + job.output.getName().getString()), false);
        }
    }

    private static boolean isOurRecipe(Recipe<?> recipe, String recipeType) {
        Identifier type = Registries.RECIPE_TYPE.getId(recipe.getType());
        return type != null && recipeType.equals(type.toString());
    }

    private static RecipeEntry<?> findRecipe(MinecraftServer server, Identifier id) {
        for (RecipeEntry<?> entry : server.getRecipeManager().values()) {
            if (entry.id().equals(id)) {
                return entry;
            }
        }
        return null;
    }

    private static Identifier parseRecipeId(String raw, String recipeType) {
        String t = raw.trim();
        if (t.isEmpty()) {
            return null;
        }
        if (!t.contains(":")) {
            return Identifier.tryParse(recipeType + "/" + t);
        }
        if (!t.contains("/")) {
            return Identifier.tryParse(t.substring(0, t.indexOf(':')) + ":"
                    + recipeType.substring(recipeType.indexOf(':') + 1) + "/"
                    + t.substring(t.indexOf(':') + 1));
        }
        return Identifier.tryParse(t);
    }

    private static BlockPos findStation(ServerWorld world, BlockPos center, Identifier blockId) {
        Block def = Registries.BLOCK.get(blockId);
        if (def == null) {
            return null;
        }
        BlockPos best = null;
        double bestDist = Double.MAX_VALUE;
        for (int dx = -STATION_RANGE; dx <= STATION_RANGE; dx++) {
            for (int dy = -2; dy <= 2; dy++) {
                for (int dz = -STATION_RANGE; dz <= STATION_RANGE; dz++) {
                    BlockPos pos = center.add(dx, dy, dz);
                    if (!world.getBlockState(pos).isOf(def)) {
                        continue;
                    }
                    double d = center.getSquaredDistance(pos);
                    if (d < bestDist) {
                        bestDist = d;
                        best = pos;
                    }
                }
            }
        }
        return best;
    }

    /** 站点下方 1 格是热源，或者它自己带 LIT 属性且为真（营火 / 炉灶）。 */
    private static boolean isHeated(ServerWorld world, BlockPos station, TagKey<Block> heatSources) {
        var below = world.getBlockState(station.down());
        if (below.isIn(heatSources)) {
            return true;
        }
        return below.contains(Properties.LIT) && below.get(Properties.LIT);
    }

    private static int cookTimeOf(Recipe<?> recipe, int declaredDefault) {
        try {
            Method m = recipe.getClass().getMethod("getCookTime");
            Object v = m.invoke(recipe);
            if (v instanceof Number n && n.intValue() > 0) {
                return n.intValue();
            }
        } catch (Throwable ignored) {
            // the mod may expose it under another name; fall back to the declared default
        }
        return declaredDefault;
    }

    private static List<ItemStack> snapshot(ServerPlayerEntity player) {
        List<ItemStack> stacks = new ArrayList<>();
        for (int i = 0; i < player.getInventory().size(); i++) {
            stacks.add(player.getInventory().getStack(i));
        }
        return stacks;
    }

    private static void commit(ServerPlayerEntity player, List<ItemStack> stacks) {
        for (int i = 0; i < stacks.size(); i++) {
            player.getInventory().setStack(i, stacks.get(i));
        }
    }

    /**
     * 从背包里扣掉一件"能当这个原料用"的东西。
     *
     * 两层匹配：先按"物品 + 组件"精确比对（最准），再退回只比物品。
     * 退回这一层是为了带自定义组件的原料（数据包改过的、耐久不同的），
     * 否则配方认它、扣料却找不到，白报"缺料"。
     */
    private static boolean takeOne(List<ItemStack> stacks, ItemStack[] candidates) {
        for (ItemStack stack : stacks) {
            if (stack.isEmpty()) {
                continue;
            }
            for (ItemStack candidate : candidates) {
                if (ItemStack.areItemsAndComponentsEqual(stack, candidate)) {
                    stack.decrement(1);
                    return true;
                }
            }
        }
        for (ItemStack stack : stacks) {
            if (stack.isEmpty()) {
                continue;
            }
            for (ItemStack candidate : candidates) {
                if (stack.isOf(candidate.getItem())) {
                    stack.decrement(1);
                    return true;
                }
            }
        }
        return false;
    }

    private static String describe(Ingredient ingredient) {
        ItemStack[] stacks = ingredient.getMatchingStacks();
        return stacks.length == 0 ? "?" : stacks[0].getName().getString();
    }

    private static int fail(ServerCommandSource source, String message) {
        source.sendError(Text.literal(message));
        return 0;
    }

    // ---- config ----

    static final class SidecarStation {
        final String id;
        final String label;
        final String command;
        final Identifier block;
        final String recipeType;
        final int cookTime;
        final int opLevel;
        final TagKey<Block> heatTagKey;

        SidecarStation(String id, String label, String command, String block, String recipeType,
                       int cookTime, int opLevel, String heatTag) {
            this.id = id;
            this.label = label == null || label.isBlank() ? id : label;
            this.command = command == null || command.isBlank() ? id : command;
            this.block = Identifier.of(block);
            this.recipeType = recipeType;
            this.cookTime = cookTime > 0 ? cookTime : 200;
            this.opLevel = Math.max(0, opLevel);
            this.heatTagKey = heatTag == null || heatTag.isBlank()
                    ? null
                    : TagKey.of(RegistryKeys.BLOCK, Identifier.of(heatTag));
        }
    }

    private static List<SidecarStation> loadStations() {
        List<SidecarStation> out = new ArrayList<>();
        Path dir = FabricLoader.getInstance().getConfigDir().resolve("modsmith-sidecar");
        if (!Files.isDirectory(dir)) {
            return out;
        }
        Gson gson = new Gson();
        try (Stream<Path> files = Files.list(dir)) {
            for (Path file : files.filter(p -> p.getFileName().toString().endsWith(".json")).toList()) {
                JsonObject root = gson.fromJson(Files.readString(file), JsonObject.class);
                if (root == null || !root.has("stations")) {
                    LOG.warn("[modsmith-sidecar] {} has no stations array, skipped", file.getFileName());
                    continue;
                }
                JsonArray stations = root.getAsJsonArray("stations");
                for (JsonElement el : stations) {
                    JsonObject st = el.getAsJsonObject();
                    out.add(new SidecarStation(
                            require(st, "id"),
                            opt(st, "label"),
                            opt(st, "command"),
                            require(st, "block"),
                            require(st, "recipeType"),
                            st.has("cookTime") ? st.get("cookTime").getAsInt() : 0,
                            st.has("opLevel") ? st.get("opLevel").getAsInt() : 2,
                            opt(st, "heatTag")));
                }
            }
        } catch (Exception e) {
            LOG.error("[modsmith-sidecar] failed to read config: {}", e.toString());
        }
        return out;
    }

    private static String require(JsonObject o, String key) {
        JsonElement v = o.get(key);
        if (v == null || v.isJsonNull()) {
            throw new IllegalArgumentException("station config missing '" + key + "'");
        }
        return v.getAsString();
    }

    private static String opt(JsonObject o, String key) {
        JsonElement v = o.get(key);
        return v == null || v.isJsonNull() ? null : v.getAsString();
    }

    private static final class CookJob {
        final ServerPlayerEntity player;
        final ItemStack output;
        int remaining;

        CookJob(ServerPlayerEntity player, ItemStack output, int remaining) {
            this.player = player;
            this.output = output;
            this.remaining = remaining;
        }
    }
}
