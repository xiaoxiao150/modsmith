/**
 * @param {Record<string, any>} args
 * @param {{fatal: (m: string) => never}} io
 */
export default async function cmdSidecar(args, io) {
  const manifestPath = args._[1];
  if (!manifestPath) io.fatal('sidecar 要给一个 manifest 路径');
  const manifest = readManifest(manifestPath);
  if (!manifest) io.fatal(`读不了 manifest：${manifestPath}`);

  const stations = (manifest.stations ?? []).filter((s) => s.kind === 'sidecar-recipe');
  if (stations.length === 0) {
    io.fatal('这份 manifest 里没有 sidecar-recipe 型站点；跑 modsmith learn 先');
  }
  const only = typeof args.station === 'string' ? args.station : null;
  const targets = only ? stations.filter((s) => s.id === only) : stations;
  if (targets.length === 0) io.fatal(`没有叫「${only}」的 sidecar 站点`);

  const outRoot = String(args.out ?? './sidecars');
  const mcVersion = String(args['mc-version'] ?? '1.21.1');
  const ns = manifest.namespace ?? manifest.mod.replace(/-/g, '_');

  for (const st of targets) {
    const [, blockShort] = String(st.block).split(':');
    const cmd = commandName(st);
    const modId = ident(`${ns}_${st.id}`).toLowerCase();
    const pkg = `dev.modsmith.${ident(ns).toLowerCase()}`;
    const cls = ident(`${ns}_${st.id}`).replace(/^./, (c) => c.toUpperCase());
    const label = manifest.names?.[`block.${blockShort}`]?.zh ?? blockShort;

    const dir = join(outRoot, modId);
    const javaDir = join(dir, 'src', 'main', 'java', ...pkg.split('.'));
    const resDir = join(dir, 'src', 'main', 'resources');
    mkdirSync(javaDir, { recursive: true });
    mkdirSync(resDir, { recursive: true });

    const recipeType = st.recipeType ?? `${ns}:cooking`;
    const cookTime = 200;
    // 热源检查：站点声明了 heatTag 才生成，否则留空（不硬加规则）
    const heatTag = typeof st.heatTag === 'string' ? st.heatTag.trim() : '';
    const heatCheck = heatTag
      ? `        if (!isHeated(world, station)) {
            return fail(source, "_@@STATION_LABEL@@ is not heated: put a heat source (stove / lit campfire) under it");
        }`
      : '';
    const heatMethod = heatTag
      ? `    private static final TagKey<Block> HEAT_SOURCES =
            TagKey.of(RegistryKeys.BLOCK, Identifier.of("${heatTag.split(':')[0]}", "${heatTag.split(':')[1]}"));

    /** 站点下方 1 格是热源，或者它自己带 LIT 属性且为真（营火 / 炉灶）。 */
    private static boolean isHeated(ServerWorld world, BlockPos station) {
        var below = world.getBlockState(station.down());
        if (below.isIn(HEAT_SOURCES)) {
            return true;
        }
        return below.contains(Properties.LIT) && below.get(Properties.LIT);
    }`
      : '';

    const subs = {
      '@@PKG@@': pkg,
      '@@OPLEVEL@@': String(Number(args['op-level'] ?? 2) || 0),
      '@@HEATCHECK@@': heatCheck,
      '@@HEATMETHOD@@': heatMethod,
      '@@CLASS@@': cls,
      '@@MODID@@': modId,
      '@@MODNAME@@': manifest.mod,
      '@@NS@@': ns,
      '@@BLOCK@@': blockShort,
      '@@STATION_LABEL@@': label,
      '@@RECIPETYPE@@': recipeType,
      '@@COOKTIME@@': String(cookTime),
      '@@CMD@@': cmd,
      '@@VERSION@@': '0.1.0',
      '@@GROUP@@': `dev.modsmith`,
      '@@MCVERSION@@': mcVersion,
      '@@NAME@@': `${manifest.mod} ${label} sidecar`,
    };
    const fill = (tpl) => Object.entries(subs).reduce((acc, [k, v]) => acc.split(k).join(v), tpl);

    writeFileSync(join(javaDir, `${cls}Mod.java`), fill(JAVA_TEMPLATE), 'utf8');
    writeFileSync(join(dir, 'build.gradle'), fill(BUILD_GRADLE), 'utf8');
    writeFileSync(join(dir, 'settings.gradle'), fill(SETTINGS_GRADLE), 'utf8');
    writeFileSync(join(dir, 'gradle.properties'), 'org.gradle.jvmargs=-Xmx3G\norg.gradle.daemon=false\n', 'utf8');
    writeFileSync(join(resDir, 'fabric.mod.json'), fill(FABRIC_MOD_JSON), 'utf8');
    writeFileSync(join(dir, 'README.md'), fill(README), 'utf8');

    // 命令名要回写到 manifest，机器人才知道怎么调
    st.command = `/${cmd} cook {recipe}`;
    st.recipeType = recipeType;

    console.error(`✓ ${st.id} → ${dir}`);
    console.error(`   命令 /${cmd} cook <recipe>，配方类型 ${recipeType}`);
  }

  // 命令名变化要落盘，否则 learn 学的对不上
  const { writeManifest } = await import('./manifest-io.mjs');
  writeManifest(manifestPath, manifest);
  console.error(`  已把 command 写回 ${manifestPath}`);

  console.error('\n⚠️  生成的模组**没有**被安装到任何服务器。');
  console.error('   先用 gradle build 编译，再在临时服上验一遍，确认后才考虑生产服。');
  console.log(outRoot);
}
