/**
 * `modsmith sidecar` —— 给 `sidecar-recipe` 型站点生成服务端侧车模组。
 *
 * 为什么需要它：有些站点的菜单是模组私有的，服务端不给原版协议客户端发 `open_window`
 * （农夫乐事厨锅实测七种手势都不发）。机器人拿不到界面就没法用，只能在服务端替它做。
 *
 * **安全边界（这是生成代码进别人服务器的东西，必须守住）：**
 *   1. 只做一件事：查 RecipeManager → 验料 → 扣料 → 等熟成 → 给成品。不碰文件、网络、
 *      反射（只反射读 mod 自己的 cookTime，读不到就用 200 tick）。
 *   2. 绝不自动安装：生成完只写一个目录，装不装由人决定。CLI 会明确提示。
 *   3. 源码留在工程里，可读可审。
 *
 * 模板取自 `Cortico-mod-fdchef`（已实机验证可编译、可用）。
 */
import { mkdirSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
